import type { LucideIcon } from "lucide-react";
import {
  Ban,
  ShieldAlert,
  Lock,
  Scale,
  PiggyBank,
  GraduationCap,
  Users,
  Megaphone,
  MessageSquareWarning,
  HeartHandshake,
  ScrollText,
  Eye,
  Leaf,
  Award,
  HeartPulse,
  TrendingUp,
  Target,
  BadgeCheck,
  ShieldCheck,
  UserCog,
  MonitorSmartphone,
  Gift,
  Landmark,
  Wallet,
} from "lucide-react";

/**
 * เลือกไอคอนประจำข้อจากคำสำคัญในเนื้อหา — ให้สมาชิกกวาดตาแล้วรู้ว่าข้อนี้เรื่องอะไร
 * โดยแอดมินไม่ต้องเลือกเอง
 *
 * ตัวแรกที่ตรงชนะ ลำดับจึงสำคัญ: คำที่บอก "หัวเรื่อง" ของข้อต้องมาก่อน
 * คำขยายที่มักโผล่ท้ายประโยค (เท่าเทียม, เสมอภาค, โปร่งใส, ไม่นำไปใช้)
 * ไม่อย่างนั้นข้อเรื่องรางวัลที่ลงท้ายว่า "ด้วยความเสมอภาค" จะได้ไอคอนตราชั่ง
 *
 * มีคำสะกดผิดที่พบใน DB จริงรวมไว้ด้วย (ทับช้อน, ข้อแย้ง, บรรอุ) เพื่อให้ยังจับได้
 * แก้ลำดับแล้วควรรันตรวจกับข้อมูลจริงทุกข้อ ไม่ใช่ดูแค่ข้อที่แก้
 */
const RULES: Array<[RegExp, LucideIcon]> = [
  [/ทับซ้อน|ทับช้อน|คู่แข่ง|ปฏิปักษ์/, Ban],
  // ประโยคเรื่องความลับมักลงท้ายว่า "ไม่นำไป..." จึงต้องมาก่อนกฎห้าม
  [/ความลับ|ข้อมูลส่วน/, Lock],
  // ไม่ใส่ "ไม่นำ" และ "ค่าตอบแทน" — กว้างเกิน ไปชนข้อทรัพย์สินและข้อการจ้างงาน
  [/ละเว้น|ไม่อาศัย|สินบน/, ShieldAlert],
  [/ร้องเรียน|เบาะแส|ประพฤติมิชอบ/, MessageSquareWarning],
  [/ข่าวสาร|รับฟัง|ข้อคิดเห็น|ข้อเสนอแนะ/, Megaphone],
  [/รางวัล|ลงโทษ/, Award],
  // ไม่ใส่ "ประสิทธิภาพ" — ข้อพัฒนาตนเองก็ใช้คำนี้
  [/กำกับ|ประสิทธิผล/, Target],
  [/เท่าเทียม|เลือกปฏิบัติ|ยุติธรรม|เสมอภาค/, Scale],
  [/ทรัพย์สิน|อุปกรณ์|ประหยัด/, PiggyBank],
  [/พัฒนาตน|ความรู้|ศักยภาพ/, GraduationCap],
  [/จ้าง|บรรจุ|บรรอุ|ทรัพยากรบุคคล/, UserCog],
  [/สามัคคี|ขัดแย้ง|ข้อแย้ง|แตกแยก/, Users],
  [/บริการ|เต็มใจ|ประทับใจ/, HeartHandshake],
  // สังคมมาก่อนความโปร่งใส — ข้อ CSR มักพูดถึง "โปร่งใส ตรวจสอบได้" ประกอบ
  [/สังคม|สิ่งแวดล้อม/, Leaf],
  [/เปิดเผย|โปร่งใส|ตรวจสอบ/, Eye],
  [/คุณภาพชีวิต|ปลอดภัย|อาชีวอนามัย/, HeartPulse],
  [/เติบโต|ยั่งยืน|มูลค่า|ผลตอบแทน/, TrendingUp],
  [/กฎหมาย|ข้อบังคับ|ระเบียบ|นโยบาย/, ScrollText],
  [/มุ่งมั่น|อุทิศ|ซื่อสัตย์|สุจริต|ผลประโยชน์ของสมาชิก/, BadgeCheck],
  // กลุ่มพันธกิจ/ค่านิยม (หน้าวิสัยทัศน์) — ไว้ท้ายสุดเพราะไม่ชนกับข้อนโยบาย/จรรยาบรรณเดิม
  // ใช้ "ระบบสารสนเทศ" ไม่ใช่ "สารสนเทศ" เฉย ๆ เพราะนโยบายข้อเปิดเผยข้อมูลมีคำนี้
  [/เทคโนโลยี|ระบบสารสนเทศ|ดิจิทัล/, MonitorSmartphone],
  [/สวัสดิการ/, Gift],
  [/ธรรมาภิบาล|ธรรมมาภิบาล/, Landmark],
  [/การเงิน|มั่นคง/, Wallet],
];

export function pickGovernanceIcon(text: string): LucideIcon {
  for (const [pattern, icon] of RULES) {
    if (pattern.test(text)) return icon;
  }
  return ShieldCheck;
}
